const importanceToPriority = {
  core: "high",
  important: "medium",
  optional: "low",
};

function createEvidence({
  marketFrequency = null,
  authoritativeSupport = [],
  jobPostingCount = 0,
  rationale,
  researchSkillNames = [],
}) {
  return {
    marketFrequency,
    authoritativeSupport: [...authoritativeSupport],
    jobPostingCount,
    researchSkillNames: [...researchSkillNames],
    rationale,
  };
}

function createSkill({
  id,
  name,
  aliases = [],
  category,
  importance,
  assessmentWeight = 0,
  targetLevel,
  assessable,
  evidence,
}) {
  return {
    id,
    name,
    aliases: [...aliases],
    category,
    importance,
    assessmentWeight,
    targetLevel,
    assessable,
    evidence,
  };
}

function toLegacySkill(skill) {
  return {
    name: skill.name,
    aliases: [...skill.aliases],
    weight: skill.assessmentWeight,
    priority: importanceToPriority[skill.importance] ?? "low",
    category: skill.category,
    targetLevel: skill.targetLevel,
    importance: skill.importance,
    skillId: skill.id,
    evidence: skill.evidence,
  };
}

function createRole({
  id,
  name,
  aliases,
  description,
  experienceLevel,
  sourceMetadata,
  skills,
  skillGroups = [],
}) {
  const requiredSkills = skills.filter((skill) => skill.assessable).map(toLegacySkill);
  const optionalSkills = skills.filter((skill) => !skill.assessable).map(toLegacySkill);
  const technicalAssessmentWeight = requiredSkills.reduce((sum, skill) => sum + skill.weight, 0);

  if (technicalAssessmentWeight !== 100) {
    throw new Error(`Technical assessment weights for ${name} must total 100.`);
  }

  return {
    id,
    name,
    aliases: [...aliases],
    description,
    experienceLevel,
    sourceMetadata: {
      ...sourceMetadata,
      evidenceSources: [...sourceMetadata.evidenceSources],
    },
    skills,
    skillGroups: [...skillGroups],
    requiredSkills,
    optionalSkills,
    technicalAssessment: {
      totalWeight: technicalAssessmentWeight,
      strategy:
        "Only assessable technical skills contribute to readiness. Core skills receive higher weights, important skills receive lower weights, and optional or soft skills remain informational.",
    },
  };
}

